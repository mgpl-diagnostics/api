// Writes docs/04-api-reference.md from the schema (operations, arguments, return types, descriptions)
// and the controllers (the permission each resolver checks). Run `npm run docs:reference`; CI fails when it is stale.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GraphQLObjectType, type GraphQLField } from "graphql";
import { buildSchema, MODULES } from "../src/graphql/schema";

// fileURLToPath, not .pathname: on Windows .pathname gives "/E:/…" with %20 for spaces
const root = fileURLToPath(new URL("..", import.meta.url));
const schema = buildSchema();

/** field → permissions found in its resolver body, per root type. */
function permissionsByField(): Record<"Query" | "Mutation", Map<string, Set<string>>> {
  const out = { Query: new Map<string, Set<string>>(), Mutation: new Map<string, Set<string>>() };
  for (const file of readdirSync(`${root}src/controllers`)) {
    const src = readFileSync(`${root}src/controllers/${file}`, "utf8");
    // helpers like `reportFor(ctx, id, "report:read")` pass the permission literally, so a literal scan is enough
    for (const kind of ["Query", "Mutation"] as const) {
      const start = src.indexOf(`\n  ${kind}: {`);
      if (start < 0) continue;
      const end = src.indexOf("\n  },", start);
      const block = src.slice(start, end);
      const keys = [...block.matchAll(/^ {4}(?:async )?(\w+)(?=\s*[:(])/gm)];
      keys.forEach((k, i) => {
        const body = block.slice(k.index!, keys[i + 1]?.index ?? block.length);
        const perms = new Set([...body.matchAll(/"([a-z]+:[a-z]+)"/g)].map((m) => m[1]!));
        const signedIn = /actorOf|authorize|viewerOrThrow|requireViewer/.test(body);
        if (!perms.size && signedIn) perms.add("(signed in)");
        out[kind].set(k[1]!, perms);
      });
    }
  }
  return out;
}

const perms = permissionsByField();
const moduleOf = new Map<string, string>();
for (const { name, typeDefs } of MODULES) {
  const sdl = String(typeDefs).replace(/"""[\s\S]*?"""/g, "");
  for (const kind of ["Query", "Mutation"]) {
    for (const m of sdl.matchAll(new RegExp(`type ${kind} \\{([\\s\\S]*?)\\n\\s*\\}`, "g")))
      for (const f of m[1]!.matchAll(/^\s+(\w+)\s*[(:]/gm)) moduleOf.set(`${kind}.${f[1]}`, name);
  }
}

const sig = (f: GraphQLField<unknown, unknown>) =>
  `${f.name}${f.args.length ? `(${f.args.map((a) => `${a.name}: ${a.type}`).join(", ")})` : ""}: ${f.type}`;
const one = (s?: string | null) => (s ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();

const lines: string[] = [
  "# 04 · API reference",
  "",
  "<!-- Generated by `npm run docs:reference` (scripts/api-reference.ts). Do not edit by hand. -->",
  "",
  "Every operation of `POST /graphql`, grouped by module, with the permission its resolver checks.",
  "**Permission** lists what `authorize()` requires; a branch-scoped permission is checked against the",
  "record's branch (see [06-auth-and-permissions.md](06-auth-and-permissions.md)). `public` means no",
  "sign-in is needed; `(signed in)` means any signed-in user. The full SDL is [schema.graphql](../schema.graphql),",
  "and runnable examples are in [examples/](examples/).",
  "",
];
for (const { name } of MODULES) {
  const rows: string[] = [];
  for (const kind of ["Query", "Mutation"] as const) {
    const type = (kind === "Query" ? schema.getQueryType() : schema.getMutationType()) as GraphQLObjectType;
    for (const f of Object.values(type.getFields()).sort((a, b) => a.name.localeCompare(b.name))) {
      if (moduleOf.get(`${kind}.${f.name}`) !== name) continue;
      const p = perms[kind].get(f.name);
      const perm = p && p.size ? [...p].map((x) => (x.startsWith("(") ? x : `\`${x}\``)).join(", ") : "public";
      rows.push(`| ${kind === "Query" ? "query" : "mutation"} | \`${sig(f)}\` | ${perm} | ${one(f.description)} |`);
    }
  }
  if (!rows.length) continue;
  lines.push(`## ${name}`, "", "| Kind | Operation | Permission | Notes |", "|---|---|---|---|", ...rows, "");
}
writeFileSync(`${root}docs/04-api-reference.md`, lines.join("\n"));
console.log(`docs/04-api-reference.md: ${lines.filter((l) => l.startsWith("| q") || l.startsWith("| m")).length} operations`);
