// Writes schema.graphql (the whole API in SDL) for clients, codegen and review. CI checks it is current.
import { writeFileSync } from "node:fs";
import { lexicographicSortSchema, printSchema } from "graphql";
import { buildSchema } from "../src/graphql/schema";

const sdl = `# Generated by \`npm run schema\` from src/schema. Do not edit by hand.\n\n${printSchema(lexicographicSortSchema(buildSchema()))}\n`;
writeFileSync("schema.graphql", sdl);
console.log(`schema.graphql: ${sdl.split("\n").length} lines`);
